def transform_body(name: str, text: str, sec_no: int, sec_title: str) -> str:
    lines = text.split("\n")
    # 去掉文件前部的标题块，直到“## 第X部分”行
    start = 0
    for i, line in enumerate(lines):
        if line.startswith("## 第") and "部分" in line:
            start = i + 1
            break
    body = "\n".join(lines[start:]).strip("\n")

    for old, new in TARGETED.get(name, []):
        body = body.replace(old, new)
    for old, new in GLOBAL:
        body = body.replace(old, new)

    # 三级标题 “### N.M 标题” → “（一）标题”
    counter = [0]
    out_lines = []
    for line in body.split("\n"):
        m = re.match(r"^###\s+\d+\.\d+\s+(.*)$", line)
        if m:
            counter[0] += 1
            out_lines.append(f"#### （{cn_num(counter[0])}）{m.group(1)}")
        else:
            out_lines.append(line)
    body = "\n".join(out_lines)

    head = f"### {cn_num(sec_no)}、{sec_title}"
    return head + "\n\n" + body


def main() -> None:
    chunks = [FRONT.read_text(encoding="utf-8").strip("\n")]
    for name, sec_head, sec_no, sec_title in STRUCT:
        text = (SRC / name).read_text(encoding="utf-8")
        if sec_head:
            chunks.append("---\n\n## " + sec_head)
        chunks.append(transform_body(name, text, sec_no, sec_title))
    doc = "\n\n".join(chunks) + "\n"
    for old, new in POST:
        if old not in doc:
            print("警告：未匹配 ", old[:30])
        doc = doc.replace(old, new)
    # 图表题注规范：去掉题注末尾句号
    doc = re.sub(r"^([图表]\s*1-\d+\s*[^。\n]*)。$", r"\1", doc, flags=re.M)
    OUT.write_text(doc, encoding="utf-8")

    # 诊断
    print("输出：", OUT.name)
    print("总字符数：", len(doc))
    print("汉字数：", len(re.findall(r"[\u4e00-\u9fff]", doc)))
    print("--- 标题结构 ---")
    for line in doc.split("\n"):
        if re.match(r"^#{1,4}\s", line):
            print(line)
    print("--- 图表出现顺序 ---")
    for line in doc.split("\n"):
        if re.match(r"^[图表]\s*1-\d+", line.strip()):
            print(line.strip())


if __name__ == "__main__":
    main()
